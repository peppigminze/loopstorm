import { loadData, ok, summary } from './load.js';
import { mulberry32, hashStr, pickWeighted } from '../logic/rng.js';
import { computeStats, modText } from '../logic/stats.js';
import { defaultSave, sanitizeSave, loadSave, storeSave, memoryStorage, SAVE_KEY } from '../logic/save.js';
const data = loadData();
const r1 = mulberry32(5), r2 = mulberry32(5);
ok(r1() === r2(), 'rng deterministisch');
ok(hashStr('abc') === hashStr('abc'), 'hash');
let cnt = { a: 0, b: 0 }; const rr = mulberry32(1);
for (let i = 0; i < 1000; i++) cnt[pickWeighted(rr, [{ id: 'a', w: 9 }, { id: 'b', w: 1 }]).id]++;
ok(cnt.a > 800 && cnt.b > 50, 'weighted ' + JSON.stringify(cnt));
const s = defaultSave();
const st = computeStats(data, s, 'komet', null);
ok(st.maxHp === 100 && st.loopDmg === 40, 'basis stats');
s.skills.a1 = 2; const st2 = computeStats(data, s, 'komet', { wucht: 1 });
ok(Math.abs(st2.loopDmg - 40 * (1 + 2 * data.skillMap.a1.mods[0].p + 0.2)) < 0.01, 'mods ' + st2.loopDmg);
const st3 = computeStats(data, s, 'komet', { glut: 1, kette: 1 });
ok(st3.flags.chainBurn && st3.synergies.includes('brandkette'), 'synergie');
ok(modText({ s: 'loopDmg', p: 0.1 }) === '+10% Schleifenschaden', 'modText');
const mem = memoryStorage();
ok(loadSave(mem, data).fresh, 'leer -> fresh');
mem.setItem(SAVE_KEY, '{kaputt'); const l = loadSave(mem, data);
ok(l.corrupt && l.save.level === 1 && mem.getItem(SAVE_KEY + '_corrupt'), 'kaputter save');
const weird = sanitizeSave({ dust: 'x', level: -3, skills: { a1: 99, zz: 3 }, equipped: { kern: 7 }, inventory: [{ uid: 'q' }], settings: { sound: 5 } }, data);
ok(weird.dust === 0 && weird.level === 1 && weird.skills.a1 === data.skillMap.a1.max && !('zz' in weird.skills) && weird.equipped.kern === null && weird.inventory.length === 0 && weird.settings.sound === true, 'sanitize');
s.dust = 55; storeSave(mem, s); ok(loadSave(mem, data).save.dust === 55, 'roundtrip');
ok(sanitizeSave(null, data).level === 1, 'null save');
process.exitCode = summary('M1');
