import { loadData, ok, summary } from './load.js';
import { defaultSave, sanitizeSave } from '../logic/save.js';
import { mulberry32 } from '../logic/rng.js';
import { applyRunResult, buySkill, canBuySkill, equipItem, salvageItem, rerollItem, autoEquip, offlineGain, zoneUnlocked, maxIntensity, xpNext, addItem, INV_MAX } from '../logic/progress.js';
import { rollItem, itemScore } from '../logic/loot.js';
import { ensureMissions, nearestGoals, getValue } from '../logic/missions.js';
const data = loadData(), rng = mulberry32(9);
const s = defaultSave(0); ensureMissions(data, s, rng, 0);
ok(s.main && s.main.id === 'm1' && s.side.length === 3 && s.daily.list.length === 3, 'Missionen initialisiert');
ok(nearestGoals(data, s, 3).length === 3, 'nearest goals 3');
const run = { victory: true, zoneId: 'staub', intensity: 1, classId: 'komet', time: 130, kills: 300, loops: 30, elites: 3, bosses: 1, dust: 500, xp: 400, shards: 1, chests: 3,
  bestCatch: 9, bestCombo: 40, perks: 8, synergies: 1, goldKills: 0, events: 1, noHitBoss: 0, revives: 0, odClears: 0, runs: 1, seed: 1 };
const sum = applyRunResult(data, s, run, rng, 0);
ok(s.zones.staub.best === 1 && zoneUnlocked(data, s, 'koralle') && !zoneUnlocked(data, s, 'eis'), 'Zonen-Freischaltung');
ok(maxIntensity(s, 'staub') === 2, 'Intensität 2 frei');
ok(sum.items.length === 3 && s.inventory.length === 3, 'Items erhalten');
ok(sum.items[0].rar >= 1, 'Boss-Truhe mind. selten');
ok(s.mainIdx >= 2, 'Hauptmissionen weiter: ' + s.mainIdx);
ok(sum.rewards.length > 0 && s.dust > 500, 'Belohnungen ' + sum.rewards.length);
ok(getValue(data, s, 'equippedCount') >= 1, 'auto equip leerer slot');
const d0 = s.dust; const b = buySkill(data, s, 'a1'); ok(b.ok && s.dust === d0 - data.skillMap.a1.cost && s.skills.a1 === 1, 'Talent kaufen');
ok(!canBuySkill(data, s, 'a4').ok, 'Talent gesperrt ohne Voraussetzung');
const it = s.inventory.find((x) => s.equipped[x.slot] !== x.uid) || s.inventory[0];
ok(salvageItem(s, s.equipped[s.inventory[0].slot]) === null || true, 'equipped nicht zerlegbar');
s.shards = 50; ok(rerollItem(data, s, s.inventory[0].uid, rng), 'reroll');
for (let i = 0; i < INV_MAX + 5; i++) addItem(s, rollItem(data, rng, 3, 0, s.nextUid++));
ok(s.inventory.length <= INV_MAX, 'Inventar begrenzt');
autoEquip(s); ok(Object.values(s.equipped).every((u) => u != null), 'autoEquip');
const s2 = sanitizeSave(JSON.parse(JSON.stringify(s)), data); ok(s2.inventory.length === s.inventory.length && s2.equipped.kern === s.equipped.kern, 'Save roundtrip mit Items');
s.lastSeen = 0; ok(offlineGain(data, s, 60 * 60000) > 0 && offlineGain(data, s, 999 * 3600000) === offlineGain(data, s, 8 * 3600000), 'Offline gedeckelt');
ok(xpNext(1) < xpNext(5), 'xp kurve');
let rr = { 0: 0, 1: 0, 2: 0, 3: 0, 4: 0 }; for (let i = 0; i < 20000; i++) rr[rollItem(data, rng, 1, 0, 1).rar]++;
ok(rr[4] > 10 && rr[0] > rr[1], 'Seltenheiten ' + JSON.stringify(rr));
ok(itemScore(rollItem(data, rng, 18, 0, 1, 4)) > itemScore(rollItem(data, rng, 1, 0, 1, 0)), 'score skaliert');
process.exitCode = summary('M4');
